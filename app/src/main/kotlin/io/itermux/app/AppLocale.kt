enum class AppLanguage(val label: String) {
    ZH_CN("简体中文"), ENGLISH("English");

    companion object {
        fun from(value: String?) = entries.firstOrNull { it.name == value } ?: ZH_CN
    }
}

/** A single observable language choice also covers text outside Compose, such as notifications. */
object AppLocale {
    var language by mutableStateOf(AppLanguage.ZH_CN)
        private set

    fun initialize(context: Context) {
        language = AppLanguage.from(context.getSharedPreferences("app-settings", Context.MODE_PRIVATE).getString("language", null))
    }

    fun set(context: Context, value: AppLanguage) {
        context.getSharedPreferences("app-settings", Context.MODE_PRIVATE).edit { putString("language", value.name) }
        language = value
    }
}

fun tr(chinese: String): String = if (AppLocale.language == AppLanguage.ENGLISH) EnglishText.values[chinese] ?: chinese else chinese

fun trf(pattern: String, vararg args: Any): String = tr(pattern).format(*args)

